コンストラクタを使って、これらのプロパティに値をセットできるようにしてください。

fetchDiscountedPrice というメソッドを作成し、そのメソッドで特技に応じて割引価格を返すようにしてください。特技が「歌」なら10%割引、「ダンス」なら5%割引、「その他」なら割引なし。

価格は price というプロパティで、商品価格を設定できるようにしてください。割引後の価格を表示するようにしてください。

