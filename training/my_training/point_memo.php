Hero クラスに $name と $unit というプロパティを持たせ、describe メソッドで「〇〇は〇〇チームのメンバーです」と出力してください。

以下のコードを完成させてください：

<?php

class Hero {
    // ここにプロパティを定義してください
    public $name;
    public $unit;
    
    // メソッドを定義してください
    public function describe($name, $unit) {
        // ここに処理を書いてください
        echo $name . "は" . $unit . "チームのメンバーです\n";
    }
}

$Hoshirube = new Hero();
$Hoshirube->describe("星導ショウ", "Dytica"); // 出力: 星導ショウはDyticaチームのメンバーです。

$Usami = new Hero();
