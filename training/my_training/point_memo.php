🟡AIの出してくれたポイント🟡

・describe メソッド内では引数を取らず、インスタンスのプロパティ ($this->name や $this->unit) を使って出力します。

・コンストラクタでインスタンスごとに名前とユニットを初期化しています。ここです！🔴

・これで、describe メソッドを呼び出す際に、毎回名前やユニット名を渡す必要がなくなり、$Hoshirube や $Usami のインスタンスで自動的に正しい情報が出力されるよ！

